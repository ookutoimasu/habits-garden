import { TreeStage } from './types';

/**
 * Предварительная художественная и биологическая модель дерева (treeConfig.ts).
 *
 * ПРИНЯТЫЕ ДОПУЩЕНИЯ:
 * 1. Непрерывность во времени:
 *    Состояние дерева вычисляется интегрированием по времени (почасовыми/суточными шагами)
 *    от момента создания привычки `createdAtMs` до переданного `nowMs`.
 *    Отметка выполнения или достижение дневной цели таймера в момент T меняет только
 *    скорость роста (производную) ПОСЛЕ момента T. В сам момент T размер ствола,
 *    ветвление и густота кроны остаются строго непрерывными (скачок = 0).
 * 2. Свободное расписание по 7-дневным периодам:
 *    Периоды по 7 локальных календарных дней отсчитываются последовательно от даты создания.
 *    Пока текущий 7-дневный период не завершён, отсутствие выполнений в те дни, когда у
 *    пользователя ещё остаётся достаточно дней для выполнения плана (или в обычные дни отдыха
 *    при плане N < 7), НЕ считается пропуском и не снижает жизненность.
 * 3. Полноценность любого выбранного плана:
 *    Скорость развития и восстановления нормируется на выбранную цель `targetDaysPerWeek` (от 1 до 7).
 *    Поэтому выполнение плана 3 из 3 за неделю даёт точно такой же недельный вклад в развитие
 *    и восстановление кроны, как выполнение 7 из 7 при ежедневном плане.
 * 4. Увядание и сохранение дерева:
 *    При запустении (когда просрочено выполнение плана или долго нет занятий) рост `development`
 *    плавно останавливается, `vitality` и `canopyRecovery` снижаются: сначала листья тускнеют,
 *    затем опадают. Примерно через 16–18 дней полного отсутствия занятий (в рамках ориентира 14–21 день)
 *    дерево переходит в состояние голого ствола с сухими ветвями (`canopyRecovery = 0`, `vitality = 0`),
 *    но само дерево и его ветви никогда не исчезают и не откатываются в развитии.
 * 5. Постепенное восстановление:
 *    После сильного увядания возвращение к занятиям сначала пробуждает почки (`budFactor`),
 *    затем постепенно возвращает листву. Полное восстановление кроны от голого ствола до 100%
 *    занимает около 21 дня (три недели) выполнения выбранного недельного плана.
 *    Старые пропуски не накапливают «бесконечный долг»: жизненность и крона ограничены диапазоном [0..1].
 */
export const TREE_CONFIG = {
  /** Начальные параметры только что посаженного ростка */
  initialDevelopment: 4.0,
  initialVitality: 0.92,
  initialCanopy: 0.88,

  /**
   * Пороги стадий развития (в единицах development, где 1 неделя 100%-го выполнения плана
   * при хорошей жизненности приносит `developmentPerFullWeek` единиц).
   * - Росток в маленьком горшке: 0 .. 18 (~первые 2.5–3 недели)
   * - Молодое дерево: 18 .. 45 (~от 3 до 8 недель)
   * - Крупное дерево в кадке: 45 .. 80 (~от 2 до 4 месяцев)
   * - Зрелое дерево в земле: 80+ (~от 4 месяцев и далее)
   */
  stageThresholds: {
    sproutMax: 18,
    youngMax: 45,
    largeMax: 80,
    maxVisualDevelopment: 120,
  },

  /** Прирост развития за одну полную неделю выполнения плана (при 100% жизненности) */
  developmentPerFullWeek: 5.5,

  /**
   * Коэффициент распределения роста во времени после выполнения:
   * Каждое выполненное занятие создаёт «импульс питания» (nourishment), который
   * плавно усваивается деревом в течение следующих 24 часов, обеспечивая непрерывный рост
   * без мгновенного скачка в секунду нажатия.
   */
  nourishmentWindowHours: 24,

  /**
   * Параметры увядания (запустения):
   * После начала фактического пропуска (когда план периода уже нарушен или период завершён
   * без выполнения нормы, либо нет активности дольше допустимого интервала)
   * жизненность и крона снижаются до 0 примерно за 16–18 суток.
   */
  neglectGraceDaysForFullPlan: 1.5,
  daysToBareTrunkUnderNeglect: 17.0,

  /**
   * Параметры восстановления:
   * Полное восстановление кроны после сильного увядания занимает ~21 день (3 недели)
   * соблюдения выбранного плана.
   */
  recoveryWeeksForFullCanopy: 3.0,
  vitalityRecoveryWeeks: 2.0,

  /** Минимальная жизненность, при которой продолжается структурный рост ствола и ветвей */
  minVitalityForGrowth: 0.35,

  /** Порог кроны, при котором на ветвях активно видны молодые почки восстановления */
  budPeakCanopyRange: {
    min: 0.05,
    peak: 0.35,
    max: 0.75,
  },
} as const;

export function getStageFromDevelopment(development: number): TreeStage {
  if (development < TREE_CONFIG.stageThresholds.sproutMax) {
    return 'sprout';
  }
  if (development < TREE_CONFIG.stageThresholds.youngMax) {
    return 'young';
  }
  if (development < TREE_CONFIG.stageThresholds.largeMax) {
    return 'large';
  }
  return 'mature';
}

export function getStageLabelRu(stage: TreeStage): string {
  switch (stage) {
    case 'sprout':
      return 'Росток в маленьком горшке';
    case 'young':
      return 'Молодое дерево';
    case 'large':
      return 'Крупное дерево в кадке';
    case 'mature':
      return 'Зрелое дерево в земле';
  }
}

export function getConditionLabelRu(vitality: number, canopyRecovery: number): string {
  if (canopyRecovery <= 0.04) {
    return 'Голый ствол, дерево ждёт ухода';
  }
  if (canopyRecovery < 0.35 && vitality >= 0.45) {
    return 'Пробуждаются почки, крона восстанавливается';
  }
  if (vitality < 0.35 || canopyRecovery < 0.4) {
    return 'Листья тускнеют и опадают';
  }
  if (vitality < 0.68 || canopyRecovery < 0.72) {
    return 'Спокойное состояние, крона набирает силу';
  }
  return 'Здоровое живое дерево';
}
